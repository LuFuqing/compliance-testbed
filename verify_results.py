def check_supplementary_sobol_samples(rep: Report):
    """results/sobol_samples.csv -- the sensitivity inputs and outputs.

    The strongest available check is not a row count: it is that the released
    indices can be *recomputed from this file alone*, by the same estimators the
    analysis used and without touching the engine.  If the samples and the
    indices ever disagree, one of them is wrong and this fails.
    """
    rep.section("SUPPLEMENTARY -- sensitivity input/output samples")
    rows = read_csv("sobol_samples.csv")

    blocks = {}
    for r in rows:
        blocks.setdefault(r["block"], []).append(r)

    rep.check_true("10144 rows = 4000 MC + 2x1024 Saltelli + 4x1024 AB",
                   len(rows) == 10144, f"{len(rows)} rows")
    rep.check_true("MC block has 4000 rows", len(blocks.get("MC_first_order", [])) == 4000)
    rep.check_true("A and B blocks have 1024 rows each",
                   len(blocks.get("A_saltelli", [])) == 1024
                   and len(blocks.get("B_saltelli", [])) == 1024)
    rep.check_true("one AB block per factor, 1024 rows each",
                   all(len(blocks.get(f"AB_{n}", [])) == 1024
                       for n in ("p_err", "p_skip", "p_atk", "n_stakeholders")))
    rep.check_true("both targets reported on every row",
                   all(r["y_M6_conformance_score"] != ""
                       and r["y_M1_evidence_completeness"] != "" for r in rows))

    # every input stays inside the declared sampling space
    from experiments.sobol import SPACE
    rep.check_true("all sampled inputs lie inside SPACE",
                   all(0.0 <= float(r["x_p_err"]) <= 1.0
                       and 0.0 <= float(r["x_p_skip"]) <= 1.0
                       and 0.0 <= float(r["x_p_atk"]) <= 1.0
                       and 0.0 <= float(r["x_n_stakeholders"]) <= 1.0 for r in rows))

    # ---- recompute S1 and ST from the file, and compare with sobol.csv ----
    from experiments.sobol import NAMES, _var, s1_binned, DEFAULT_BINS

    def mat(block):
        return [[float(r["x_p_err"]), float(r["x_p_skip"]),
                 float(r["x_p_atk"]), float(r["x_n_stakeholders"])]
                for r in blocks[block]]

    MC = mat("MC_first_order")
    A_, B_ = mat("A_saltelli"), mat("B_saltelli")
    ab = {n: mat(f"AB_{n}") for n in NAMES}

    idx = {(r["target"], r["param"]): r for r in read_csv("sobol.csv")}
    for target in ("M6_conformance_score", "M1_evidence_completeness"):
        y = [float(r[f"y_{target}"]) for r in blocks["MC_first_order"]]
        # DEFAULT_BINS, not a literal: if the paper's bin count changes, this
        # check must move with it rather than silently recompute at the old value.
        s1 = s1_binned(MC, y, DEFAULT_BINS)
        rep.check_true(
            f"S1 recomputed from the sample file matches sobol.csv [{target[:2]}]",
            all(abs(s1[i] - num(idx[(target, n)], "S1")) <= 1e-4
                for i, n in enumerate(NAMES)),
            str([round(v, 4) for v in s1]))

        yA = [float(r[f"y_{target}"]) for r in blocks["A_saltelli"]]
        yB = [float(r[f"y_{target}"]) for r in blocks["B_saltelli"]]
        var = _var(yA + yB)
        n = len(yA)
        st = []
        for name in NAMES:
            yAB = [float(r[f"y_{target}"]) for r in blocks[f"AB_{name}"]]
            st.append(0.5 * sum((yA[j] - yAB[j]) ** 2 for j in range(n)) / n / var)
        rep.check_true(
            f"ST recomputed from the sample file matches sobol.csv [{target[:2]}]",
            all(abs(st[i] - num(idx[(target, n)], "ST")) <= 1e-4
                for i, n in enumerate(NAMES)),
            str([round(v, 4) for v in st]))

    rep.check_true("rows are written in evaluation order, 0..n-1 per block",
                   all([int(r["row"]) for r in blk] == list(range(len(blk)))
                       for blk in blocks.values()),
                   f"{len(blocks)} blocks")


def check_supplementary_estimator(rep: Report):
    """results/estimator_validation.csv -- Table 7 of the manuscript.

    Every panel is asserted at its printed values, which it can be, because both
    panels are now computed at one bin count (``DEFAULT_BINS`` = 10) with a
    recorded seed. Panel A used not to be: its printed values were consistent
    only with B = 10 while Section 4.4 stated 12, and no seed reproduced them, so
    the check only asked whether they lay inside the estimator's own spread.
    """
    from experiments.sobol import DEFAULT_BINS

    rep.section("SUPPLEMENTARY -- estimator validation (Table 7)")
    rows = read_csv("estimator_validation.csv")

    def get(panel, func, i, bins=DEFAULT_BINS):
        for r in rows:
            if (r["panel"] == panel and r["test_function"] == func
                    and int(r["bins"]) == bins and int(r["factor_index"]) == i):
                return r
        raise KeyError((panel, func, bins, i))

    rep.check_true(f"20 rows = panel A 2 funcs x 4 factors + panel B 3 x 4, all at B = {DEFAULT_BINS}",
                   len(rows) == 20, f"{len(rows)} rows")
    rep.check_true("one bin count for both panels, recorded rather than assumed",
                   {int(r["bins"]) for r in rows} == {DEFAULT_BINS})

    # ---- panel B: Saltelli and the substitute, at their printed values --------
    # Saltelli and Jansen do not use binning, so their columns must be unchanged
    # by a bin-count switch; only the substituted column moves. That asymmetry is
    # the cheapest cross-check that the switch did what it was supposed to do.
    panel_b = [
        ("additive  f = 0.5 + a(x0 + x1)", [1.1548, 0.9718], [0.4964, 0.4932]),
        ("interaction f = 0.5 + b*x0*x1", [-0.0387, 0.9169], [0.4274, 0.4216]),
        ("single  f = 0.5 + c*x0", [1.9273, 0.0], [0.9902, 0.0016]),
    ]
    for func, salt, sub in panel_b:
        got_s = [num(get("B", func, i), "saltelli_S1_N1024") for i in (0, 1)]
        got_b = [num(get("B", func, i), "substituted_S1_N4000") for i in (0, 1)]
        rep.check_true(f"panel B Saltelli S1 matches Table 7 [{func[:11]}]",
                       all(abs(a - b) <= 5e-4 for a, b in zip(got_s, salt)),
                       str([round(v, 4) for v in got_s]))
        rep.check_true(f"panel B substituted S1 matches Table 7 [{func[:11]}]",
                       all(abs(a - b) <= 5e-4 for a, b in zip(got_b, sub)),
                       str([round(v, 4) for v in got_b]))

    add_func = "additive  f = 0.5 + a(x0 + x1)"
    ssum = sum(num(get("B", add_func, i), "saltelli_S1_N1024") for i in range(4))
    rep.check_true("panel B additive Saltelli sum ~ 2.13 (the printed overestimate)",
                   2.10 < ssum < 2.16, f"sum = {ssum:.4f}")

    # the substitute is unbiased where Saltelli is not
    rep.check_true("panel B additive: substitute lands on the true 0.5 where Saltelli reads 1.15",
                   all(abs(num(get("B", add_func, i), "substituted_S1_N4000") - 0.5) < 0.02
                       for i in (0, 1)))
    int_func = "interaction f = 0.5 + b*x0*x1"
    rep.check_true("panel B pure interaction: substitute is biased upward (the stated caveat)",
                   all(num(get("B", int_func, i), "substituted_S1_N4000") > 0.35
                       for i in (0, 1)),
                   "true S1 = 0, binned reads ~0.43")
    rep.check_true("panel B single factor: Saltelli exceeds unity, substitute does not",
                   num(get("B", "single  f = 0.5 + c*x0", 0), "saltelli_S1_N1024") > 1.5
                   and num(get("B", "single  f = 0.5 + c*x0", 0),
                           "substituted_S1_N4000") < 1.0)

    # ---- panel A: now reproducible, so asserted to the digit -----------------
    panel_a = [
        ("additive  f = x0 + 2x1", [0.198696, 0.791502]),
        ("single  f = x0", [0.990238, 0.001561]),
    ]
    for func, want in panel_a:
        got = [num(get("A", func, i), "substituted_S1_N4000") for i in (0, 1)]
        rep.check_true(f"panel A substituted S1 matches Table 7 [{func[:11]}]",
                       all(abs(a - b) <= 5e-4 for a, b in zip(got, want)),
                       str([round(v, 4) for v in got]))

    # the analytic structure the table exists to show
    rep.check_true("panel A additive recovers the true 0.200 / 0.800",
                   abs(num(get("A", "additive  f = x0 + 2x1", 0),
                           "substituted_S1_N4000") - 0.2) < 0.03
                   and abs(num(get("A", "additive  f = x0 + 2x1", 1),
                               "substituted_S1_N4000") - 0.8) < 0.02,
                   f"{num(get('A', 'additive  f = x0 + 2x1', 0), 'substituted_S1_N4000')} / "
                   f"{num(get('A', 'additive  f = x0 + 2x1', 1), 'substituted_S1_N4000')}")
    rep.check_true("panel A single factor recovers the true 1.000 / 0.000",
                   num(get("A", "single  f = x0", 0),
                       "substituted_S1_N4000") > 0.98)
    # The binned estimator's large-N limit for a single factor is exactly
    # 1 - 1/B^2; the ensemble mean should sit on it. This is the invariant that
    # makes the bin count a reportable parameter in the first place.
    want_limit = 1.0 - 1.0 / (DEFAULT_BINS ** 2)
    rep.check_true(
        f"panel A single factor hits the analytic ceiling 1 - 1/B^2 = {want_limit:.4f}",
        abs(float(get("A", "single  f = x0", 0)["ensemble_mean"]) - want_limit) <= 1e-3,
        f"ensemble mean {get('A', 'single  f = x0', 0)['ensemble_mean']}")


def check_manifest(rep: Report):
    """results/SHA256SUMS -- the archive manifest named in the availability note."""
    rep.section("SUPPLEMENTARY -- archive manifest (SHA-256)")
    path = os.path.join(RESULTS, "SHA256SUMS")
    if not os.path.exists(path):
        rep.check_true("results/SHA256SUMS exists", False)
        return

    want = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line:
                digest, _, rel = line.partition("  ")
                want[rel] = digest

    rep.check_true("manifest lists the three new supplementary tables",
                   {"results/stress_contrast.csv", "results/sobol_samples.csv",
                    "results/estimator_validation.csv"} <= set(want))
    rep.check_true("manifest lists the engine and rule set (source, not just data)",
                   any(r.startswith("engine/") for r in want)
                   and any(r.startswith("ruleset/") for r in want))

    bad = []
    for rel, digest in want.items():
        p = os.path.join(_ROOT, rel)
        if not os.path.exists(p):
            bad.append(f"absent:{rel}")
        elif sha256(p) != digest:
            bad.append(f"digest:{rel}")
    rep.check_true("every listed digest still matches the file on disk",
                   not bad, f"{len(want)} entries" if not bad else str(bad[:5]))

    listed = set(want)
    on_disk = set()
    for dirpath, _d, filenames in os.walk(RESULTS):
        for fn in filenames:
            if fn in (".DS_Store", "SHA256SUMS"):
                continue
            on_disk.add(os.path.relpath(os.path.join(dirpath, fn), _ROOT)
                        .replace(os.sep, "/"))
    rep.check_true("no regenerated result is missing from the manifest",
                   on_disk <= listed, str(sorted(on_disk - listed)[:5]))


def check_release_metadata(rep: Report):
    rep.section("RELEASE METADATA")
    cff = os.path.join(_ROOT, "CITATION.cff")
    if os.path.exists(cff):
        text = open(cff, encoding="utf-8").read()
        rep.check_true("CITATION.cff present", True)
        if "CHANGEME" in text:
            print("  [WARN] CITATION.cff still contains the repository placeholder "
                  "'CHANGEME' -- fill it in before publishing (see RELEASE.md).")
    else:
        rep.check_true("CITATION.cff present", False)

    # ---------------------------------------------------------- placeholders
    # Everything that must be filled in by the author before deposit, in one
    # place. These are warnings, not failures: a placeholder is a correct state
    # for a working tree and an incorrect one for a published archive, and only
    # the author can tell which this is. The scan exists so that no placeholder
    # can be missed -- NOTICE previously carried a bare <DOI> that nothing looked at.
    #
    # RELEASE.md is deliberately NOT scanned: its job is to *describe* the
    # placeholders and show the commands that remove them, so it contains the
    # strings by construction.
    PLACEHOLDERS = ("CHANGEME", "<DOI", "<REPOSITORY-URL>")
    SCAN = ["CITATION.cff", "NOTICE", "README.md", "Makefile",
            "reproduce.sh", "make_release.py", "make_manifest.py", "VERSION"]
    found = []
    for rel in SCAN:
        p = os.path.join(_ROOT, rel)
        if not os.path.exists(p):
            continue
        for i, line in enumerate(open(p, encoding="utf-8"), 1):
            for ph in PLACEHOLDERS:
                if ph in line:
                    found.append(f"{rel}:{i}: {ph}")
    if found:
        print(f"\n  [WARN] {len(found)} author placeholder(s) still present in the release")
        print("         metadata -- these must be resolved or deliberately kept before the")
        print("         artifact is deposited:")
        for f in found:
            print(f"           {f}")
        print("         See RELEASE.md, section 1b (deposit checklist).")
    else:
        print("\n  [ok]   no author placeholders remain in the release metadata")

    for rel in ("LICENSE", "LICENSE-DATA", "NOTICE", "CHANGELOG.md", "VERSION",
                "README.md", "RESULTS.md", "reproduce.sh", "CITATION.cff",
                "make_manifest.py", "make_release.py"):
        rep.check_true(f"present: {rel}", os.path.exists(os.path.join(_ROOT, rel)))

    # Regression guard: an authored document inside results/ would be destroyed by
    # `reproduce.sh --clean`, because that directory is treated as fully regenerable.
    stray = os.path.join(RESULTS, "RESULTS.md")
    rep.check_true("authored docs are outside results/ (survive a clean rebuild)",
                   not os.path.exists(stray),
                   "results/ holds only regenerable artifacts" if not os.path.exists(stray)
                   else "results/RESULTS.md exists and would be deleted by --clean")

    generated = {".csv", ".json", ".png", ".svg", ".pdf"}
    # SHA256SUMS has no extension by convention; it is generated by make_manifest.py
    # and lives under results/ on purpose, so that `reproduce.sh --clean` governs it.
    allowed_names = {"SHA256SUMS"}
    unexpected = []
    for dirpath, _dirnames, filenames in os.walk(RESULTS):
        for fn in filenames:
            if fn == ".DS_Store" or fn in allowed_names:
                continue
            if os.path.splitext(fn)[1] not in generated:
                unexpected.append(os.path.relpath(os.path.join(dirpath, fn), _ROOT))
    rep.check_true("results/ contains only generated artifact types", not unexpected,
                   "all files are csv/json/png (plus SHA256SUMS)" if not unexpected
                   else str(unexpected))

    rep.check_true(
        "licence split: MIT for code, CC BY 4.0 for data",
        os.path.exists(os.path.join(_ROOT, "LICENSE"))
        and os.path.exists(os.path.join(_ROOT, "LICENSE-DATA")),
    )


def check_fingerprints(rep: Report, strict: bool, manifest_only: bool):
    print(f"\nRELEASE FINGERPRINTS ({'hard gate' if strict else 'advisory'})")
    print("-" * 78)
    drift = []
    for name, want in FINGERPRINTS.items():
        path = os.path.join(RESULTS, name)
        if not os.path.exists(path):
            drift.append((name, want, "MISSING"))
            print(f"  [FAIL] {name:<28} MISSING")
            continue
        got = md5(path)
        if got == want or manifest_only:
            print(f"  [ok]   {name:<28} {got}")
        else:
            drift.append((name, want, got))
            print(f"  [{'FAIL' if strict else 'WARN'}] {name:<28} {got}")
            print(f"         {'':<28} expected {want}")
    if drift and strict:
        rep.failed.append("release fingerprints")
        rep.check_true("fingerprints match the recorded release run", False,
                       f"{len(drift)} file(s) drifted")
    elif drift:
        print("\n  NOTE: fingerprints drifted from the recorded release run. If a modelled")
        print("        parameter was deliberately re-calibrated, refresh FINGERPRINTS")
        print("        in verify_results.py and re-verify RESULTS.md against the new")
        print("        numbers. Otherwise this is an unintended regression.")
    else:
        rep.check_true("fingerprints match the recorded release run", True)


