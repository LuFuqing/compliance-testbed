"""Supplementary tables promised by the manuscript's data-availability note.

Paper 4 states, in the data-availability section, that the supplementary
material contains

  (a) the complete scenario definitions,
  (b) the full stress-contrast table with injected-mislabel counts and
      interval estimates,
  (c) sensitivity input and output samples,
  (d) analytic validation of the sensitivity estimators in both output
      regimes, and
  (e) an archive manifest with SHA-256 digests,

and that all of them are regenerated by the same reproduction script as the
main results.

  (a) -> results/scenarios.csv, results/scenarios.json   (run_all.py)
  (b) -> results/stress_contrast.csv                     (run_stress_contrast)
  (c) -> results/sobol_samples.csv                       (sobol.run_sobol)
  (d) -> results/estimator_validation.csv                (run_estimator_validation)
  (e) -> results/SHA256SUMS                              (reproduce.sh)

Everything in this module is *additive*.  It re-reads quantities the released
results already rest on -- the raw injection/detection counts behind M3 and
M3s, and the analytic validation of the first-order estimators -- and writes
them out in full.  No metric definition, parameter, seed or random-number
draw is touched, so the four release fingerprints are unaffected.

Standard library only.
"""
from __future__ import annotations

import csv
import os
import sys
from typing import Dict, List, Optional, Tuple

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

from engine import metrics as M                        # noqa: E402
from experiments.calibration import run_event          # noqa: E402
# Panel A (ordinary output scale) and panel B (low-variance regime) both live in
# experiments/estimator_validation.py; it is re-exported here so that a caller
# needs a single import for the whole supplementary set.
from experiments.estimator_validation import run_validation as run_estimator_validation  # noqa: E402,F401
from experiments.run_scenarios import run_all_scenarios  # noqa: E402

RESULTS_DIR = os.path.join(_ROOT, "results")

# ---------------------------------------------------------------- (b) stress contrast

STRESS_COLS = [
    "scope", "run", "name", "profile", "mode",
    "load", "p_err", "p_skip", "p_atk", "n_handovers",
    "n_injected", "n_detected", "n_injected_undetected",
    "n_mislabels_injected", "n_mislabels_detected", "n_mislabels_undetected",
    "M3s", "M3s_ci_low", "M3s_ci_high",
]


def _count_row(scope: str, run: str, name: str, bundles, extra: Dict) -> Dict:
    c = M.detection_counts(bundles)
    lo, hi = M.wilson_interval(c["n_mislabels_detected"],
                               c["n_mislabels_injected"])
    row = {
        "scope": scope, "run": run, "name": name,
        "n_injected": c["n_injected"],
        "n_detected": c["n_detected"],
        "n_injected_undetected": c["n_injected_undetected"],
        "n_mislabels_injected": c["n_mislabels_injected"],
        "n_mislabels_detected": c["n_mislabels_detected"],
        "n_mislabels_undetected": c["n_mislabels_undetected"],
        "M3s": (round(c["n_mislabels_detected"] / c["n_mislabels_injected"], 4)
                if c["n_mislabels_injected"] else ""),
        "M3s_ci_low": "" if lo is None else lo,
        "M3s_ci_high": "" if hi is None else hi,
    }
    row.update(extra)
    return row


def run_stress_contrast(verbose: bool = True) -> List[Dict]:
    """Write results/stress_contrast.csv and return its rows.

    Two scopes in one file:

      scope=phase     the six SL/T 853-855 process phases, under the stressed
                      run and under the nominal (fair-weather) control run;
      scope=scenario  the ten entries of the scenario suite.

    The mislabel counts are the sample sizes behind M3s; the Wilson interval is
    the two-sided 95% interval for the same ratio.  They are reported because
    the per-phase counts are single digits, where a rate without an interval is
    not interpretable -- which is why the manuscript withdraws the claim that
    the silent channel widens under load.
    """
    rows: List[Dict] = []

    for label, stressed in (("stressed", True), ("nominal", False)):
        sink: List[Tuple[dict, list]] = []
        run_event(stressed=stressed, sink=sink)
        for row, bundles in sink:
            rows.append(_count_row(
                "phase", label, row["phase"], bundles,
                {"profile": "flood", "mode": "B2",
                 "load": row["load"], "p_err": row["p_err"],
                 "p_skip": row["p_skip"], "p_atk": row["p_atk"],
                 "n_handovers": row["n_handovers"]},
            ))

    sink = []
    run_all_scenarios(verbose=False, sink=sink)
    for row, bundles in sink:
        rows.append(_count_row(
            "scenario", "", row["scenario"], bundles,
            {"profile": row["profile"], "mode": row["mode"],
             "load": "", "p_err": row["p_err"], "p_skip": row["p_skip"],
             "p_atk": row["p_atk"], "n_handovers": row["n_handovers"]},
        ))

    os.makedirs(RESULTS_DIR, exist_ok=True)
    path = os.path.join(RESULTS_DIR, "stress_contrast.csv")
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=STRESS_COLS)
        w.writeheader()
        w.writerows(rows)

    if verbose:
        print("\nStress contrast -- injected-mislabel counts and Wilson intervals")
        print(f"{'scope':<10}{'run':<10}{'name':<24}{'hand':>6}{'inj':>5}"
              f"{'det':>5}{'mis':>5}{'misd':>6}{'M3s':>8}   95% Wilson")
        print("-" * 92)
        for r in rows:
            m3s = r["M3s"]
            ci = ("-" if r["M3s_ci_low"] == ""
                  else f"[{r['M3s_ci_low']:.3f}, {r['M3s_ci_high']:.3f}]")
            print(f"{r['scope']:<10}{r['run']:<10}{r['name']:<24}"
                  f"{r['n_handovers']:>6}{r['n_mislabels_injected']:>5}"
                  f"{r['n_mislabels_detected']:>5}"
                  f"{r['n_mislabels_injected']:>5}"
                  f"{r['n_mislabels_detected']:>6}"
                  f"{(f'{m3s:.3f}' if m3s != '' else '-'):>8}   {ci}")
        print(f"\n[written] {path}")
    return rows


# ------------------------------------------------------------ (d) estimator validation
# run_estimator_validation is re-exported from experiments.estimator_validation
# at the top of this module (see the import block).


if __name__ == "__main__":
    run_stress_contrast()
    run_estimator_validation()
