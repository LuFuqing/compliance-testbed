#!/usr/bin/env python3
"""Golden-value verification of the released results.

This is the gate that turns "the code runs" into "the reported numbers are
reproducible". It re-reads the generated ``results/`` files and asserts the
substantive claims made in ``RESULTS.md`` and in the manuscript.

Two tiers of check, deliberately kept separate:

  1. GOLDEN CHECKS (hard gate, tolerance 1e-3 unless stated)
     The numeric claims the paper actually rests on. A failure here means
     either a regression in the model or a results file that does not match
     the text -- both must be fixed before release.

  2. RELEASE FINGERPRINTS (advisory by default, error under --strict)
     MD5 digests of the four generated CSVs, recorded at release time. They
     are *not* a correctness criterion: a legitimate re-calibration of a
     modelled parameter will change them. They exist so that an unintended
     drift is noticed rather than silently published.

Usage
-----
    python3 verify_results.py            # golden checks + advisory fingerprints
    python3 verify_results.py --strict   # fingerprints become a hard gate
    python3 verify_results.py --skip-figures
                                         # tolerate absent PNGs (no matplotlib)
    python3 verify_results.py --manifest # print the fingerprint manifest only

Standard library only. Exit code 0 = pass, 1 = failure.
"""
