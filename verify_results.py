# ---------------------------------------------------------------- helpers
class Report:
    def __init__(self):
        self.passed = 0
        self.failed: list[str] = []

    def check(self, label: str, actual, expected, tol: float = TOL) -> bool:
        try:
            ok = abs(float(actual) - float(expected)) <= tol
        except (TypeError, ValueError):
            ok = (actual == expected)
            shown_a, shown_e = repr(actual), repr(expected)
        else:
            shown_a, shown_e = f"{float(actual):.6g}", f"{float(expected):.6g}"
        if ok:
            self.passed += 1
            print(f"  [ok]   {label:<62} {shown_a}")
        else:
            self.failed.append(label)
            print(f"  [FAIL] {label:<62} got {shown_a}  expected {shown_e}")
        return ok

    def check_true(self, label: str, cond: bool, detail: str = "") -> bool:
        if cond:
            self.passed += 1
            print(f"  [ok]   {label:<62} {detail}")
        else:
            self.failed.append(label)
            print(f"  [FAIL] {label:<62} {detail}")
        return cond

    def section(self, title: str):
        print(f"\n{title}")
        print("-" * 78)


def read_csv(name: str) -> list[dict]:
    path = os.path.join(RESULTS, name)
    if not os.path.exists(path):
        raise SystemExit(
            f"missing {path}\n"
            "Run ./reproduce.sh first (or: python3 run_all.py && python3 run_stress_sensitivity.py)."
        )
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def num(row: dict, col: str):
    v = row.get(col, "")
    return None if v in ("", None) else float(v)


def by_key(rows: list[dict], key: str) -> dict:
    return {r[key]: r for r in rows}


def png_size(path: str) -> tuple[int, int] | None:
    """Return (width, height) from the IHDR chunk, or None if not a valid PNG."""
    try:
        with open(path, "rb") as fh:
            head = fh.read(24)
    except OSError:
        return None
    if len(head) < 24 or head[:8] != b"\x89PNG\r\n\x1a\n" or head[12:16] != b"IHDR":
        return None
    return struct.unpack(">II", head[16:24])


def md5(path: str) -> str:
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------- checks
def check_artifacts(rep: Report, skip_figures: bool = False):
    rep.section("ARTIFACTS")
    for rel in EXPECTED_FILES:
        if skip_figures and rel.endswith(".png"):
            continue
        rep.check_true(f"exists: {rel}", os.path.exists(os.path.join(_ROOT, rel)))

    if skip_figures:
        print("  [skip] figure checks disabled (--skip-figures)")
        return

    # the four figures must be real, non-trivial, 300-dpi-scale PNGs
    for n in (1, 2, 3, 4):
        rel = f"results/figures/fig{n}_" + {
            1: "scenarios", 2: "sensitivity", 3: "event_phases", 4: "generality",
        }[n] + ".png"
        p = os.path.join(_ROOT, rel)
        size = png_size(p)
        kh = os.path.getsize(p) / 1024 if os.path.exists(p) else 0
        rep.check_true(
            f"valid PNG: fig{n}", size is not None,
            f"{size[0]}x{size[1]} px, {kh:.0f} KB" if size else "not a PNG",
        )
        if size:
            rep.check_true(f"fig{n} plausible raster size", kh > 50, f"{kh:.0f} KB")


def check_t9_scenarios(rep: Report):
    rep.section("SCENARIO SUITE -- scenario comparison (the decisive-control claim)")
    rows = read_csv("scenarios.csv")
    s = by_key(rows, "scenario")

    rep.check_true("10 scenarios present", len(rows) == 10, f"{len(rows)} rows")

    # (1) no design -> collapse
    rep.check("B0 M1 completeness", num(s["B0_none"], "M1_evidence_completeness"), 0.0, 1e-9)
    rep.check("B0 M2 audit cost", num(s["B0_none"], "M2_audit_prep_time"), 5.8233)
    rep.check("B0 M6 conformance", num(s["B0_none"], "M6_conformance_score"), 0.193)
    rep.check("B0 M5 tamper resilience", num(s["B0_none"], "M5_tamper_resilience"), 0.0, 1e-9)

    # (2) THE headline: partial design (labels+encryption+audit, no signing)
    #     still yields ZERO verifiable completeness.
    rep.check("B1 M1 completeness (still 0 without signing)",
              num(s["B1_partial"], "M1_evidence_completeness"), 0.0, 1e-9)
    rep.check("B1 M6 conformance (lifted but insufficient)",
              num(s["B1_partial"], "M6_conformance_score"), 0.5439)
    rep.check_true(
        "B1 has labels/audit yet M1 == B0 M1 (signing is the pivot)",
        num(s["B1_partial"], "M1_evidence_completeness")
        == num(s["B0_none"], "M1_evidence_completeness"),
    )

    # (3) full design
    rep.check("S0 M1 completeness", num(s["S0_full_baseline"], "M1_evidence_completeness"), 0.9808)
    rep.check("S0 M2 audit cost", num(s["S0_full_baseline"], "M2_audit_prep_time"), 0.1183)
    rep.check("S0 M5 tamper resilience", num(s["S0_full_baseline"], "M5_tamper_resilience"), 1.0)
    rep.check("S0 M6 conformance", num(s["S0_full_baseline"], "M6_conformance_score"), 0.9905)
    rep.check_true(
        "M2 reduction B0 -> S0 is ~49x",
        abs(num(s["B0_none"], "M2_audit_prep_time")
            / num(s["S0_full_baseline"], "M2_audit_prep_time") - 49.2) < 0.5,
        f"{num(s['B0_none'], 'M2_audit_prep_time') / num(s['S0_full_baseline'], 'M2_audit_prep_time'):.1f}x",
    )

    # (4) the ~40% silent-misclassification blind spot
    #     M3s is a PLATEAU, not a point: it must barely move across attack, signature
    #     skip, topology and scale -- that insensitivity IS the finding.
    m3s = [num(r, "M3s_mislabel_detection") for r in rows
           if r["mode"] == "B2" and r["profile"] == "flood"
           and num(r, "M3s_mislabel_detection") is not None]
    rep.check_true("flood B2 M3s plateau near 0.58", all(0.57 <= v <= 0.59 for v in m3s),
                   f"values={sorted(round(v, 4) for v in m3s)}")
    rep.check_true("M3s plateau spread < 0.01 (insensitive to attack/skip/topology/scale)",
                   max(m3s) - min(m3s) < 0.01, f"spread = {max(m3s) - min(m3s):.4f}")
    rep.check_true("M3s blind spot is ~40%", 0.40 < (1 - max(m3s)) < 0.45,
                   f"1-M3s = {1 - max(m3s):.3f}")
    rep.check("S1: raising mislabel rate does depress M3",
              num(s["S1_mislabel_high"], "M3_violation_detection"), 0.7941)
    rep.check_true("S1: M3 below the S0 baseline",
                   num(s["S1_mislabel_high"], "M3_violation_detection")
                   < num(s["S0_full_baseline"], "M3_violation_detection"))

    # (5) structure moves latency, not conformance
    rep.check("S3 mesh latency", num(s["S3_mesh_topology"], "M4_handover_latency"), 0.8495)
    rep.check("S5 N=12 latency", num(s["S5_scale_N12"], "M4_handover_latency"), 1.5115)
    rep.check_true(
        "topology invariance: M6(mesh) == M6(star)",
        abs(num(s["S3_mesh_topology"], "M6_conformance_score")
            - num(s["S0_full_baseline"], "M6_conformance_score")) < 1e-9,
    )
    rep.check_true(
        "scale invariance: M6(N=12) == M6(N=5)",
        abs(num(s["S5_scale_N12"], "M6_conformance_score")
            - num(s["S0_full_baseline"], "M6_conformance_score")) < 1e-9,
    )
    rep.check_true("mesh cuts latency", num(s["S3_mesh_topology"], "M4_handover_latency")
                   < num(s["S0_full_baseline"], "M4_handover_latency"))
    rep.check_true("N=12 raises latency", num(s["S5_scale_N12"], "M4_handover_latency")
                   > num(s["S0_full_baseline"], "M4_handover_latency"))

    # (6) attack is survivable only via the signed attestation
    rep.check("S4 M1 under attack", num(s["S4_adversarial"], "M1_evidence_completeness"), 0.910)
    rep.check("S4 M2 under attack", num(s["S4_adversarial"], "M2_audit_prep_time"), 0.3308)
    rep.check("S4 M5 recovered", num(s["S4_adversarial"], "M5_tamper_resilience"), 1.0)
    rep.check("S2 M5 with skipped signatures", num(s["S2_unsigned_high"], "M5_tamper_resilience"), 0.9286)

    # (7) RQ-E generality: trend consistency, not equal magnitude
    rep.check("S6 transport M1", num(s["S6_transport_baseline"], "M1_evidence_completeness"), 0.985)
    rep.check("S6 transport M6", num(s["S6_transport_baseline"], "M6_conformance_score"), 0.9908)
    rep.check("S6b transport adversarial M1", num(s["S6b_transport_adv"], "M1_evidence_completeness"), 0.9267)
    rep.check_true(
        "RQ-E: both profiles show M1 drop under attack",
        num(s["S4_adversarial"], "M1_evidence_completeness")
        < num(s["S0_full_baseline"], "M1_evidence_completeness")
        and num(s["S6b_transport_adv"], "M1_evidence_completeness")
        < num(s["S6_transport_baseline"], "M1_evidence_completeness"),
    )
    rep.check_true(
        "RQ-E: both profiles hold M6 above 0.95",
        min(num(s["S0_full_baseline"], "M6_conformance_score"),
            num(s["S6_transport_baseline"], "M6_conformance_score"),
            num(s["S4_adversarial"], "M6_conformance_score"),
            num(s["S6b_transport_adv"], "M6_conformance_score")) > 0.95,
    )


