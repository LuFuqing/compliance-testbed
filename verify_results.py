def check_t10_sobol(rep: Report):
    rep.section("SENSITIVITY -- Sobol decomposition (the control-inversion claim)")
    rows = read_csv("sobol.csv")
    idx = {(r["target"], r["param"]): r for r in rows}

    # M6 conformance
    rep.check("M6 p_atk S1", num(idx[("M6_conformance_score", "p_atk")], "S1"), 0.4004)
    rep.check("M6 p_atk ST", num(idx[("M6_conformance_score", "p_atk")], "ST"), 0.4388)
    rep.check("M6 p_skip S1", num(idx[("M6_conformance_score", "p_skip")], "S1"), 0.2588)
    rep.check("M6 p_err S1", num(idx[("M6_conformance_score", "p_err")], "S1"), 0.2492)
    # Binned estimator at B = 10: n_stakeholders takes exactly ten integer values
    # (3..12), so each bin holds one distinct level and the index drops to ~0.002.
    rep.check("M6 n_stakeholders S1", num(idx[("M6_conformance_score", "n_stakeholders")], "S1"), 0.0019, 5e-3)

    # M1 completeness
    rep.check("M1 p_skip S1", num(idx[("M1_evidence_completeness", "p_skip")], "S1"), 0.5296)
    rep.check("M1 p_atk S1", num(idx[("M1_evidence_completeness", "p_atk")], "S1"), 0.2749)
    rep.check("M1 p_err S1", num(idx[("M1_evidence_completeness", "p_err")], "S1"), 0.0940)
    rep.check("M1 n_stakeholders S1", num(idx[("M1_evidence_completeness", "n_stakeholders")], "S1"), 0.0015, 5e-3)

    # THE key result: the two compliance objectives are governed by DIFFERENT controls
    m6 = max(("p_atk", "p_skip", "p_err"),
             key=lambda p: num(idx[("M6_conformance_score", p)], "S1"))
    m1 = max(("p_atk", "p_skip", "p_err"),
             key=lambda p: num(idx[("M1_evidence_completeness", p)], "S1"))
    rep.check_true("M6 dominant factor = p_atk (attack)", m6 == "p_atk", f"argmax = {m6}")
    rep.check_true("M1 dominant factor = p_skip (signature discipline)", m1 == "p_skip",
                   f"argmax = {m1}")
    rep.check_true("CONTROL INVERSION: argmax(M6) != argmax(M1)", m6 != m1,
                   f"M6:{m6} vs M1:{m1}")
    rep.check_true("M1 dominant factor exceeds 50% of variance",
                   num(idx[("M1_evidence_completeness", "p_skip")], "S1") > 0.5,
                   f"S1 = {num(idx[('M1_evidence_completeness', 'p_skip')], 'S1')}")

    # misclassification is the most interactive factor (propagates down the pipeline)
    for target in ("M6_conformance_score", "M1_evidence_completeness"):
        inter = {p: num(idx[(target, p)], "interaction") for p in ("p_atk", "p_skip", "p_err")}
        top = max(inter, key=inter.get)
        rep.check_true(f"{target[:2]}: largest interaction term is p_err", top == "p_err",
                       f"{inter}")

    # scale confirmed a non-factor by a second, variance-based method
    for target in ("M6_conformance_score", "M1_evidence_completeness"):
        rep.check(f"{target[:2]} n_stakeholders ST (no effect)",
                  num(idx[(target, "n_stakeholders")], "ST"), 0.0, 1e-9)

    # first-order budget + residual interaction
    for target, want in (("M6_conformance_score", 0.9103), ("M1_evidence_completeness", 0.9000)):
        tot = sum(num(idx[(target, p)], "S1") for p in ("p_atk", "p_skip", "p_err", "n_stakeholders"))
        rep.check(f"sum(S1) {target[:2]}", tot, want, 2e-3)
